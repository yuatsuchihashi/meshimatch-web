/**
 * プロフィールの食事制限プリセットからジャンル別ペナルティスコアを算出する。
 * 複数プリセットが選択されている場合、最も厳しい（最も低い）スコアを採用。
 * strictness が "flexible" の場合はペナルティを半減（0.5倍）。
 */
export function calculateDietaryGenreScores(
  presetIds: string[],
  strictness: "flexible" | "needOptions" = "needOptions"
): Record<string, number> {
  const scores: Record<string, number> = {};
  const multiplier = strictness === "flexible" ? 0.5 : 1.0;

  for (const presetId of presetIds) {
    const preset = DIETARY_PRESETS.find((p) => p.id === presetId);
    if (!preset) continue;

    for (const [genreId, score] of Object.entries(preset.genreScores)) {
      const adjusted = score * multiplier;
      scores[genreId] = Math.min(scores[genreId] ?? 0.0, adjusted);
    }
  }

  return scores;
}
